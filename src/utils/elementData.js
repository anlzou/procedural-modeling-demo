/**
 * 将原始 table 数组格式（symbol, name, mass, col, row）转换为索引映射
 * 便于通过元素索引查找完整数据
 */
export function getElementDetail(index) {
  if (index < 0 || index >= ELEMENTS.length) return null
  const e = ELEMENTS[index]
  return {
    symbol: e[0],
    name: e[1],
    mass: e[2],
    column: e[3],
    row: e[4],
    chineseName: e[5],
    category: e[6],
    electronConfig: e[7],
    meltPoint: e[8],
    boilPoint: e[9],
    discovered: e[10],
    description: e[11],
    number: index + 1,
  }
}

/**
 * 搜索元素
 * @param {string} query 搜索关键词
 * @returns {Array<{index: number, detail: object}>} 匹配结果
 */
export function searchElements(query) {
  if (!query || query.length === 0) return []
  const q = query.toLowerCase()
  const results = []
  for (let i = 0; i < ELEMENTS.length; i++) {
    const e = ELEMENTS[i]
    if (e[0].toLowerCase().includes(q) ||      // 符号
        e[1].toLowerCase().includes(q) ||       // 英文名
        e[5].includes(q)) {                      // 中文名
      results.push({ index: i, detail: getElementDetail(i) })
    }
  }
  return results
}
